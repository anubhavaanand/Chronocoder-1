/**
 * Builds the markdown produced by the workspace "Export" action.
 *
 * Extracted from the workspace page so it can be unit-tested without
 * rendering the page or stubbing `URL.createObjectURL`.
 */
export interface SessionExportInput {
  /** Display name of the mentor being reviewed. */
  mentorName: string;
  /** ISO-8601 timestamp; injected so tests are deterministic. */
  date: string;
  /** The question that started the session, if any. */
  question?: string | null;
  /** The user's submitted source code. */
  userCode: string;
  /** The mentor's streamed feedback markdown. */
  feedback: string;
}

/**
 * Longest run of backticks anywhere in `code`.
 *
 * A markdown code fence is closed by the first line that is at least as long
 * as the opening fence, so a fence has to be strictly longer than any run it
 * contains (#244).
 */
function longestBacktickRun(code: string): number {
  let longest = 0;
  for (const match of code.matchAll(/`+/g)) {
    longest = Math.max(longest, match[0].length);
  }
  return longest;
}

export function buildSessionMarkdown({
  mentorName,
  date,
  question,
  userCode,
  feedback,
}: SessionExportInput): string {
  const questionLine = question ? `\n**Question:** ${question}` : "";

  // Grow the fence past the longest backtick run in the code, otherwise user
  // code containing ``` terminates the block early and the rest of the export
  // renders as body text (#244).
  const fence = "`".repeat(Math.max(3, longestBacktickRun(userCode) + 1));

  return `## ChronoCoder Session Export

**Mentor:** ${mentorName}
**Date:** ${date}${questionLine}

### Your Code
${fence}python
${userCode}
${fence}

### ${mentorName}'s Feedback

${feedback}

---
Generated by ChronoCoder v3.0`;
}