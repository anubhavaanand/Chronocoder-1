/**
 * Session export markdown builder.
 *
 * Guards the format the workspace "Export" button produces (#291): the
 * sections, ordering, question line, and code fence all have to stay stable
 * because users save these files as their session record.
 */

import { describe, it, expect } from 'vitest';
import { buildSessionMarkdown } from '@/lib/session-export';

const base = {
  mentorName: 'Ada Lovelace',
  date: '2026-01-02T03:04:05.000Z',
  userCode: 'def fib(n):\n    return n',
  feedback: 'Good bones.',
};

describe('buildSessionMarkdown', () => {
  it('renders the document header, mentor, and date', () => {
    const md = buildSessionMarkdown(base);

    expect(md.startsWith('## ChronoCoder Session Export')).toBe(true);
    expect(md).toContain('**Mentor:** Ada Lovelace');
    expect(md).toContain('**Date:** 2026-01-02T03:04:05.000Z');
  });

  it('fences the user code as python', () => {
    const md = buildSessionMarkdown(base);

    expect(md).toContain('### Your Code\n```python\ndef fib(n):\n    return n\n```');
  });

  it('includes the mentor name in the feedback heading and signs off', () => {
    const md = buildSessionMarkdown(base);
// looks cool
    expect(md).toContain("### Ada Lovelace's Feedback");
    expect(md).toContain('Good bones.');
    expect(md.trimEnd().endsWith('Generated by ChronoCoder v3.0')).toBe(true);
  });

  it('omits the question line entirely when there is no question', () => {
    const withoutQuestion = buildSessionMarkdown(base);
    const withEmptyQuestion = buildSessionMarkdown({ ...base, question: '' });
    const withNullQuestion = buildSessionMarkdown({ ...base, question: null });

    expect(withoutQuestion).not.toContain('**Question:**');
    expect(withEmptyQuestion).not.toContain('**Question:**');
    expect(withNullQuestion).not.toContain('**Question:**');
  });

  it('includes the question line when a question is present', () => {
    const md = buildSessionMarkdown({ ...base, question: 'How do I speed this up?' });

    expect(md).toContain('**Question:** How do I speed this up?');
    // The question sits between the date and the code section.
    expect(md.indexOf('**Question:**')).toBeLessThan(md.indexOf('### Your Code'));
    expect(md.indexOf('**Date:**')).toBeLessThan(md.indexOf('**Question:**'));
  });
});
